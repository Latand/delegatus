export type ProtoKey = keyof Strings;

export function proto(locale: Locale, key: ProtoKey, vars: Record<string, string | number> = {}): string {
  const table = locale === "uk" ? uk : en;
  return table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}
