// How each environment variable reaches a remote gate run
// (docs/design/remote-gate-runner.md §8.5). Every name the four browser drivers
// and scripts/local-gate*.ts read has a class; env-classes.test.ts fails on a
// name without one.
//
// pass        sent as is; an absolute value must stay inside the tree
// isolated    never sent; the runner sets its own
// output-dir  an absolute local directory outside the tree is remapped to
//             the run's out/<NAME>, and its files come back (§8.8)
// input-path  sent only as a path inside the tree; any other value runs here
// never       a credential: never sent
