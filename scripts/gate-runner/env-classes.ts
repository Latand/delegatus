const TABLE = new Map<string, EnvClass>([
  ...ISOLATED.map(name => [name, "isolated"] as const),
  ...NEVER.map(name => [name, "never"] as const),
  ...INPUT_PATH.map(name => [name, "input-path"] as const),
  ...OUTPUT_DIR.map(name => [name, "output-dir"] as const),
  ...PASS.map(name => [name, "pass"] as const),
]);

/** Unlisted names are never sent: a pattern such as `_DIR` would also match a
 * local configuration directory, whose files must never come back. */
export function envClass(name: string): EnvClass | undefined {
  return TABLE.get(name);
}
