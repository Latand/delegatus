export type ProtoKey = Key;
export type ProtoT = (key: Key, vars?: Record<string, string | number>) => string;

export function protoT(locale: Locale): ProtoT {
  const table: Record<Key, string> = locale === "uk" ? UK : EN;
  return (key, vars) => table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`));
}
