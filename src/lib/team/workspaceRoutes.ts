export type WorkspaceRouteDecision = typeof WORKSPACE_ROUTES[keyof typeof WORKSPACE_ROUTES];

export function workspaceRouteDecision(pathname: string): WorkspaceRouteDecision {
  const exact = WORKSPACE_ROUTES[pathname as keyof typeof WORKSPACE_ROUTES];
  if (exact) return exact;
  for (const [route, decision] of Object.entries(WORKSPACE_ROUTES)) {
    if (!route.includes("[")) continue;
    const pattern = route.split("/").map(part => part.startsWith("[...") ? ".+" : part.startsWith("[") ? "[^/]+" : part).join("/");
    if (new RegExp(`^${pattern}$`).test(pathname)) return decision;
  }
  return "owner";
}
